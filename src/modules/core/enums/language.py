""" Import necessary modules """
from enum import Enum

# Define the Enum
class Language(Enum):
    """
    Language is an enumeration that defines the different types of languages.
    Each member of the enumeration represents a specific type of language.
    """
    ENGLISH = "english"
    SPANISH = "spanish"
    FRENCH = "french"
    GERMAN = "german"
    CHINESE = "chinese"
    JAPANESE = "japanese"
    KOREAN = "korean"
    HINDI = "hindi"
